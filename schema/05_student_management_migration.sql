-- Students are created by the placement cell with the register number as the
-- initial password; this flag forces a change on first login.
ALTER TABLE users ADD COLUMN IF NOT EXISTS must_change_password BOOLEAN NOT NULL DEFAULT FALSE;

-- First-login setup (name, email, phone) and the profile reminder email.
-- Existing students count as already set up.
ALTER TABLE student_profiles ADD COLUMN IF NOT EXISTS profile_setup_completed BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE student_profiles ADD COLUMN IF NOT EXISTS profile_reminder_sent_at TIMESTAMP NULL;

-- Normalise register numbers to trimmed uppercase. The existing UNIQUE constraint on
-- roll_no then rejects duplicates regardless of the case they were typed in.
UPDATE student_profiles SET roll_no = UPPER(TRIM(roll_no))
WHERE roll_no IS NOT NULL
  AND roll_no <> UPPER(TRIM(roll_no))
  AND NOT EXISTS (SELECT 1 FROM student_profiles other
                  WHERE other.id <> student_profiles.id AND other.roll_no = UPPER(TRIM(student_profiles.roll_no)));

ALTER TABLE student_profiles DROP CONSTRAINT IF EXISTS chk_student_roll_no_normalized;
ALTER TABLE student_profiles ADD CONSTRAINT chk_student_roll_no_normalized
    CHECK (roll_no IS NULL OR roll_no = UPPER(roll_no));

-- Departments are managed data (Manage Students -> Departments). The starting rows (CSE, ECE, EEE,
-- CIVIL, MECH, MCT) and a row for any code students already carry are added by the application at
-- startup (DepartmentSeeder and DepartmentService), not by this script.
CREATE TABLE IF NOT EXISTS departments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(10)  NOT NULL,
    name        VARCHAR(100) NOT NULL,
    is_active   BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_departments_code UNIQUE (code),
    CONSTRAINT chk_departments_code_upper CHECK (code = UPPER(code))
);

